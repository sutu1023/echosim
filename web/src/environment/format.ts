export function roleTypeLabel(value: string, lang: Lang): string {
  const key = value.trim()
  if (!key) {
    return key
  }
  if (lang === 'en') {
    return ROLE_TYPE_EN[key] ?? key
  }
  return ROLE_TYPE_ZH[key] ?? key
}
